// Writes docs/TRANSLATIONS_REVIEW.md: every string the assistant shows, in
// every language, for native speakers to check. Run: npm run translations:review

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SERVER_MESSAGES, SYSTEM_PROMPT } from '../packages/agent-core/src/index';
import { TRANSLATIONS, TRANSLATION_KEYS, UI_LANGUAGES, UNVERIFIED_LANGUAGES, LANGUAGE_NAMES } from '../packages/assistant-ui/src/i18n/translations';

const NAMES = { en: 'English', pcm: 'Nigerian Pidgin', yo: 'Yoruba', ha: 'Hausa', ig: 'Igbo' } as const;
const cell = (s: string | undefined) => (s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

const out: string[] = [];
out.push('# Assistant translations: review list');
out.push('');
out.push('Generated by `npm run translations:review`. Do not edit by hand: change');
out.push('`packages/assistant-ui/src/i18n/translations.ts` (app text) or');
out.push('`packages/agent-core/src/messages.ts` (server messages), then re-run.');
out.push('');
out.push('**Status**');
out.push('');
for (const l of UI_LANGUAGES) {
  out.push(`- ${NAMES[l]} (${l}, shown as "${LANGUAGE_NAMES[l]}"): ${UNVERIFIED_LANGUAGES.includes(l) ? '**UNVERIFIED DRAFT**, needs a native speaker; keeps the "beta" label' : 'ready'}`);
}
out.push('');
out.push('How to review: read each row in your language. Check that it is natural, correct, and means the same as the English.');
out.push('Keep every `{variable}` exactly as it is (the app fills it in). Do not use em or en dashes.');
out.push('Button names (`buttons.*`) must match the server messages table below, because the assistant tells customers to tap them by name.');
out.push('');
out.push('## App text');
out.push('');
out.push(`| Key | ${UI_LANGUAGES.map((l) => NAMES[l]).join(' | ')} |`);
out.push(`|---|${UI_LANGUAGES.map(() => '---').join('|')}|`);
for (const k of TRANSLATION_KEYS) out.push(`| \`${k}\` | ${UI_LANGUAGES.map((l) => cell(TRANSLATIONS[l][k])).join(' | ')} |`);
out.push('');
out.push('## Server messages (redirects, refusals, errors, button names)');
out.push('');
out.push(`| Key | ${UI_LANGUAGES.map((l) => NAMES[l]).join(' | ')} |`);
out.push(`|---|${UI_LANGUAGES.map(() => '---').join('|')}|`);
for (const [k, v] of Object.entries(SERVER_MESSAGES.en)) {
  if (typeof v === 'string') out.push(`| \`${k}\` | ${UI_LANGUAGES.map((l) => cell((SERVER_MESSAGES[l] as any)[k])).join(' | ')} |`);
  else for (const b of Object.keys(v)) out.push(`| \`buttons.${b}\` | ${UI_LANGUAGES.map((l) => cell((SERVER_MESSAGES[l].buttons as any)[b])).join(' | ')} |`);
}
out.push('');
out.push('## Style examples given to the model');
out.push('');
out.push('These guide the tone only. Real names and prices always come from the menus.');
out.push('');
out.push('```');
out.push(SYSTEM_PROMPT.split('Style examples (for tone only; real names and prices always come from tools):\n')[1] ?? '');
out.push('```');
out.push('');

const file = join(import.meta.dirname, '..', 'docs', 'TRANSLATIONS_REVIEW.md');
writeFileSync(file, out.join('\n'));
console.log(`wrote ${file} (${TRANSLATION_KEYS.length} app strings x ${UI_LANGUAGES.length} languages)`);
